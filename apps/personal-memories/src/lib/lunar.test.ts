import { describe, expect, it } from 'vitest';

import { lunarHolidays } from './lunar.ts';

describe('lunarHolidays', () => {
  it.each([
    [
      2016,
      {
        除夕: '2016-02-07',
        春節: '2016-02-08',
        端午: '2016-06-09',
        中秋: '2016-09-15',
      },
    ],
    [
      2020,
      {
        除夕: '2020-01-24',
        春節: '2020-01-25',
        端午: '2020-06-25',
        中秋: '2020-10-01',
      },
    ],
    [
      2023,
      {
        除夕: '2023-01-21',
        春節: '2023-01-22',
        端午: '2023-06-22',
        中秋: '2023-09-29',
      },
    ],
    [
      2025,
      {
        除夕: '2025-01-28',
        春節: '2025-01-29',
        元宵: '2025-02-12',
        端午: '2025-05-31',
        七夕: '2025-08-29',
        中秋: '2025-10-06',
      },
    ],
    [
      2026,
      {
        除夕: '2026-02-16',
        春節: '2026-02-17',
        端午: '2026-06-19',
        中秋: '2026-09-25',
      },
    ],
    [
      2028,
      {
        除夕: '2028-01-25',
        春節: '2028-01-26',
        端午: '2028-05-28',
        中秋: '2028-10-03',
      },
    ],
  ])('finds the %i festivals, skipping any leap month', (year, expected) => {
    expect(lunarHolidays(year)).toMatchObject(expected);
  });
});
